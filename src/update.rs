/// Parsed semver version for comparison.
#[derive(Debug, Clone, PartialEq, Eq, PartialOrd, Ord)]
pub struct Version {
    pub major: u32,
    pub minor: u32,
    pub patch: u32,
}

impl Version {
    pub fn parse(s: &str) -> Option<Self> {
        let s = s.strip_prefix('v').unwrap_or(s);
        let parts: Vec<&str> = s.split('.').collect();
        if parts.len() != 3 {
            return None;
        }
        Some(Self {
            major: parts[0].parse().ok()?,
            minor: parts[1].parse().ok()?,
            patch: parts[2].parse().ok()?,
        })
    }

    pub fn current() -> Self {
        Self::parse(crate::build_info::BASE_VERSION).expect("invalid CARGO_PKG_VERSION")
    }
}

impl std::fmt::Display for Version {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(f, "{}.{}.{}", self.major, self.minor, self.patch)
    }
}

/// Parsed Herdr Extended CalVer used only for distribution release ordering.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
pub(crate) struct ReleaseVersion {
    year: u16,
    month: u8,
    day: u8,
    sequence: u16,
}

impl ReleaseVersion {
    pub(crate) fn parse(value: &str) -> Option<Self> {
        let mut parts = value.split('.');
        let (Some(year), Some(month), Some(day), Some(sequence), None) = (
            parts.next(),
            parts.next(),
            parts.next(),
            parts.next(),
            parts.next(),
        ) else {
            return None;
        };
        if year.len() != 4
            || month.len() != 2
            || day.len() != 2
            || sequence.is_empty()
            || sequence.starts_with('0')
            || ![year, month, day, sequence]
                .into_iter()
                .all(|part| part.bytes().all(|byte| byte.is_ascii_digit()))
        {
            return None;
        }
        let release = Self {
            year: year.parse().ok()?,
            month: month.parse().ok()?,
            day: day.parse().ok()?,
            sequence: sequence.parse().ok()?,
        };
        let leap = release.year.is_multiple_of(4)
            && (!release.year.is_multiple_of(100) || release.year.is_multiple_of(400));
        let maximum_day = match release.month {
            1 | 3 | 5 | 7 | 8 | 10 | 12 => 31,
            4 | 6 | 9 | 11 => 30,
            2 if leap => 29,
            2 => 28,
            _ => return None,
        };
        (release.year > 0 && release.day > 0 && release.day <= maximum_day && release.sequence > 0)
            .then_some(release)
    }
}

impl std::fmt::Display for ReleaseVersion {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(
            f,
            "{:04}.{:02}.{:02}.{}",
            self.year, self.month, self.day, self.sequence
        )
    }
}


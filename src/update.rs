#[cfg(not(windows))]
struct DownloadedUpdate {
    current_exe: PathBuf,
    tmp_path: Option<PathBuf>,
}

#[cfg(not(windows))]
impl Drop for DownloadedUpdate {
    fn drop(&mut self) {
        if let Some(tmp_path) = self.tmp_path.take() {
            let _ = fs::remove_file(tmp_path);
        }
    }
}

/// Download a release to a prepared executable temp file without touching the running server.
#[cfg(not(windows))]
fn download_update(release: &ReleaseInfo) -> Result<DownloadedUpdate, String> {
    let current_exe = env::current_exe().map_err(|e| format!("can't find current binary: {e}"))?;

    let parent = current_exe.parent().ok_or("can't find binary directory")?;

    // Check write permissions early
    let test_path = parent.join(".herdr-write-test");
    if let Err(e) = fs::write(&test_path, b"") {
        let _ = fs::remove_file(&test_path);
        return Err(format!(
            "install directory not writable: {} ({}). Try running with appropriate permissions.",
            parent.display(),
            e
        ));
    }
    let _ = fs::remove_file(&test_path);

    // Unique temp file (avoids races with concurrent instances)
    let tmp_path = parent.join(format!(".herdr-update-{}.tmp", std::process::id()));

    // Download the exact asset URL (pinned to the release we checked)
    let status = crate::noninteractive_process::curl_command(&release.download_url)
        .args(["--max-time", "120", "-o"])
        .arg(&tmp_path)
        .status()
        .map_err(|e| format!("download failed: {e}"))?;

    if !status.success() {
        let _ = fs::remove_file(&tmp_path);
        return Err("download failed".into());
    }

    if let Some(expected) = &release.sha256 {
        if let Err(e) = crate::checksum::verify_sha256(&tmp_path, expected) {
            let _ = fs::remove_file(&tmp_path);
            return Err(format!(
                "downloaded update checksum verification failed: {e}"
            ));
        }
        tracing::info!(sha256 = %expected, "downloaded update checksum verified");
    }

    // Make executable
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        if let Err(e) = fs::set_permissions(&tmp_path, fs::Permissions::from_mode(0o755)) {
            let _ = fs::remove_file(&tmp_path);
            return Err(format!("chmod failed: {e}"));
        }
    }

    Ok(DownloadedUpdate {
        current_exe,
        tmp_path: Some(tmp_path),
    })
}

#[cfg(not(windows))]
fn install_downloaded_update(mut update: DownloadedUpdate) -> Result<(), String> {
    let tmp_path = update
        .tmp_path
        .take()
        .ok_or("downloaded update temp file is missing")?;

    // Atomic replace — rename over the current binary.
    // On Linux, the running process keeps its fd to the old inode.
    // Next launch picks up the new file.
    if let Err(e) = fs::rename(&tmp_path, &update.current_exe) {
        let _ = fs::remove_file(&tmp_path);
        return Err(format!("failed to replace binary: {e}"));
    }

    Ok(())
}

#[cfg(windows)]
struct DownloadedWindowsInstaller {
    root: PathBuf,
    path: PathBuf,
}

#[cfg(windows)]
impl Drop for DownloadedWindowsInstaller {
    fn drop(&mut self) {
        let _ = fs::remove_dir_all(&self.root);
    }
}

#[cfg(windows)]
fn create_windows_update_temp_root() -> Result<PathBuf, String> {
    let nonce = std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .unwrap_or_default()
        .as_nanos();
    for attempt in 0..100_u8 {
        let root = env::temp_dir().join(format!(
            "herdr-update-{}-{nonce}-{attempt}",
            std::process::id()
        ));
        match fs::create_dir(&root) {
            Ok(()) => return Ok(root),
            Err(err) if err.kind() == std::io::ErrorKind::AlreadyExists => continue,
            Err(err) => {
                return Err(format!(
                    "failed to create Windows update directory {}: {err}",
                    root.display()
                ));
            }
        }
    }
    Err("failed to allocate a unique Windows update directory".to_string())
}

#[cfg(windows)]
fn download_windows_installer(release: &ReleaseInfo) -> Result<DownloadedWindowsInstaller, String> {
    if release.asset_format.as_deref() != Some("nsis") {
        return Err("selected Windows update asset is not an NSIS installer".to_string());
    }
    let expected_sha256 = release
        .sha256
        .as_deref()
        .ok_or("selected Windows update asset has no SHA-256 digest")?;
    let root = create_windows_update_temp_root()?;
    let release_version = release
        .release_version
        .ok_or("selected Windows update has no release version")?;
    let asset_name = expected_release_asset_name("windows-x86_64-installer", release_version)
        .ok_or("selected Windows update has no installer asset name")?;
    let path = root.join(asset_name);
    let download = DownloadedWindowsInstaller { root, path };

    let status = crate::noninteractive_process::curl_command(&release.download_url)
        .args(["--max-time", "120", "-o"])
        .arg(&download.path)
        .status()
        .map_err(|err| format!("failed to download Windows installer: {err}"))?;
    if !status.success() {
        return Err(format!(
            "failed to download Windows installer with status {status}"
        ));
    }
    crate::checksum::verify_sha256(&download.path, expected_sha256).map_err(|err| {
        format!("downloaded Windows installer checksum verification failed: {err}")
    })?;
    tracing::info!(sha256 = %expected_sha256, "downloaded Windows installer checksum verified");
    Ok(download)
}

